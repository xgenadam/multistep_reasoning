# what the patch must produce (the file the experiments ran on)
PATCHED = {'instructions_util.py': '188324d4764366fc85d2e50966719e89a469f21ce0b0f773ec0abe1447d62b94'}
EMPTY_SHA = hashlib.sha256(b'').hexdigest()

# What becomes local, ignored state: generated by build.py or fetched here.
GENERATED_DIRS = ('prompts', 'tests', 'reference', 'ifeval', CHECKER_DIR)
GENERATED_FILES = ('LICENSE', 'ifeval_checker/LICENSE', 'manifest.yaml')
FETCHED = ('LICENSE', 'ifeval_checker/LICENSE', CHECKER_DIR)  # the part fetch.py writes


class FetchError(Exception):
    pass


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def download(url: str, want: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as resp:
        data = resp.read()
    got = sha256_bytes(data)
    if got != want:
        raise FetchError(f'{url}: sha256 {got}, pinned {want}; refusing it')
    return data


def write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f'.{path.name}.')
    try:
        with os.fdopen(fd, 'wb') as f:
            f.write(data)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def present_ok(path: Path, want: str) -> bool:
    """True if the file is there and matches; FetchError if it is there and does not."""
    if not path.exists():
        return False
    got = sha256_file(path)
    if got != want:
        raise FetchError(f'{path}: sha256 {got}, pinned {want}; move it aside and rerun')
    return True


# ---- unified-diff applier (exact context, no fuzz) ----

HUNK = re.compile(r'^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@')


def parse_patch(patch: str) -> dict[str, list[list[str]]]:
    """{target file name (the part after the package dir): [hunk lines, ...]}."""
    files: dict[str, list[list[str]]] = {}
    current = None
    for line in patch.splitlines(keepends=True):
        if line.startswith('+++ '):
            current = files.setdefault(line[4:].strip().split('/')[-1], [])
        elif line.startswith('--- '):
            continue
        elif line.startswith('@@'):
            if current is None:
                raise FetchError('patch: hunk before a +++ line')
            current.append([line])
        elif line.startswith('\\'):
            raise FetchError('patch: "No newline at end of file" is not supported')
        elif current and line[:1] in (' ', '-', '+'):
            current[-1].append(line)
        elif line.strip():
            raise FetchError(f'patch: unexpected line {line!r}')
    return files


def apply_hunks(text: str, hunks: list[list[str]], reverse: bool = False) -> str:
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    pos = 0
    old_mark, new_mark = ('+', '-') if reverse else ('-', '+')
    for hunk in hunks:
        m = HUNK.match(hunk[0])
        if not m:
            raise FetchError(f'patch: bad hunk header {hunk[0]!r}')
        start = int(m.group(3) if reverse else m.group(1))
        start = start - 1 if start else 0
        body = hunk[1:]
        old = [ln[1:] for ln in body if ln[0] in (' ', old_mark)]
        new = [ln[1:] for ln in body if ln[0] in (' ', new_mark)]
        if start < pos or lines[start:start + len(old)] != old:
            raise FetchError(f'patch: hunk {hunk[0].strip()} does not apply exactly')
        out += lines[pos:start] + new
        pos = start + len(old)
    return ''.join(out + lines[pos:])


# ---- data.lock ----

def tree_files(root: Path = HERE) -> list[str]:
    """Every generated or fetched file under root, as sorted relative paths (no bytecode)."""
    found = [f for f in GENERATED_FILES if (root / f).is_file()]
    for d in GENERATED_DIRS:
        for p in (root / d).rglob('*'):
            if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc':
                found.append(p.relative_to(root).as_posix())
    return sorted(found)


def lock_lines(root: Path = HERE) -> list[str]:
    return [f'{sha256_file(root / f)}  {f}' for f in tree_files(root)]


def read_lock(lock: Path = LOCK) -> dict[str, str]:
    entries = {}
    for n, line in enumerate(lock.read_text().splitlines(), 1):
        m = re.fullmatch(r'([0-9a-f]{64})  (\S+)', line)
        if not m:
            raise FetchError(f'{lock}:{n}: not a "sha256  path" line: {line!r}')
        entries[m.group(2)] = m.group(1)
    return entries


def check_lock(root: Path = HERE, prefixes: tuple[str, ...] | None = None,
               lock: Path = LOCK) -> list[str]:
    """Differences between the tree and data.lock (empty when they match).

    prefixes limits the check to paths equal to, or under, one of them."""
    def wanted(path: str) -> bool:
        return prefixes is None or any(path == p or path.startswith(p + '/') for p in prefixes)

    pins = {p: s for p, s in read_lock(lock).items() if wanted(p)}
    have = [p for p in tree_files(root) if wanted(p)]
    problems = [f'missing: {p}' for p in sorted(set(pins) - set(have))]
    problems += [f'not in data.lock: {p}' for p in have if p not in pins]
    for p in have:
        if p in pins and (got := sha256_file(root / p)) != pins[p]:
            problems.append(f'sha256 differs: {p} (have {got}, locked {pins[p]})')
    return problems


# ---- the two fetch steps ----

def fetch_raw(raw: Path) -> None:
    for rel, (url, sha) in RAW_FILES.items():
        dest = raw / rel
        if present_ok(dest, sha):
            print(f'ok      {dest}')
            continue
        print(f'fetch   {url}')
        write_atomic(dest, download(url, sha))
        print(f'wrote   {dest}')
    jsonl = raw / BCB_JSONL[0]
    if present_ok(jsonl, BCB_JSONL[1]):
        print(f'ok      {jsonl}')
    else:
        print(f'todo    {jsonl}: convert_bcb.py makes it from the parquet (make bench-std)')


def fetch_checker(root: Path = HERE) -> None:
    pkg = root / CHECKER_DIR
    want = {f'{CHECKER_DIR}/{n}': PATCHED.get(n, s) for n, s in CHECKER_FILES.items()}
    want[f'{CHECKER_DIR}/__init__.py'] = EMPTY_SHA
    want['ifeval_checker/LICENSE'] = want['LICENSE'] = LICENSE_SHA
    if all(present_ok(root / p, s) for p, s in want.items()):
        print(f'ok      {pkg} (commit {CHECKER_COMMIT[:12]}, patched) and both LICENSE copies')
        return
    hunks = parse_patch(PATCH.read_text())
    if set(hunks) - set(CHECKER_FILES):
        raise FetchError(f'{PATCH}: patches files outside the pinned set: {sorted(hunks)}')
    files: dict[str, bytes] = {}
    for name, sha in CHECKER_FILES.items():
        url = f'{GH_RAW}/instruction_following_eval/{name}'
        print(f'fetch   {url}')
        data = download(url, sha)
        if name in hunks:
            data = apply_hunks(data.decode('utf-8'), hunks[name]).encode('utf-8')
            if (got := sha256_bytes(data)) != PATCHED[name]:
                raise FetchError(f'{name}: patched sha256 {got}, pinned {PATCHED[name]}')
            print(f'patched {name} ({PATCH.name})')
        files[f'{CHECKER_DIR}/{name}'] = data
    files[f'{CHECKER_DIR}/__init__.py'] = b''
    print(f'fetch   {GH_RAW}/LICENSE')
    files['ifeval_checker/LICENSE'] = files['LICENSE'] = download(f'{GH_RAW}/LICENSE', LICENSE_SHA)
    for rel, data in files.items():
        if not (root / rel).exists():
            write_atomic(root / rel, data)
            print(f'wrote   {rel}')


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--raw', type=Path, default=DEFAULT_RAW,
                    help=f'raw dataset dir (default {DEFAULT_RAW})')
    args = ap.parse_args(argv)
    try:
        fetch_raw(args.raw)
        fetch_checker()
        problems = check_lock(prefixes=FETCHED)
    except (FetchError, OSError) as exc:
        print(f'fetch.py: {exc}', file=sys.stderr)
        return 1
    if problems:
        print('fetch.py: the fetched files do not match data.lock:', file=sys.stderr)
        for p in problems:
            print(f'  {p}', file=sys.stderr)
        return 1
    print('fetched files match data.lock')
    return 0


if __name__ == '__main__':
    sys.exit(main())

#!/usr/bin/env python3
"""Fetch bench v1-std's third-party inputs by reference and verify them.

Usage (from the repo root; stdlib only, so any Python 3.12 runs it):
  .venv/bin/python -I journal/baseline/bench/v1-std/fetch.py [--raw DIR]

The repo keeps none of the datasets' or the checker's files. This script
downloads exactly what the experiments ran on, from pinned URLs, and refuses
any file whose sha256 differs from its pin:

1. The raw dataset files, into DIR (default ~/models/bench-std-raw), in the
   layout build.py reads. BigCodeBench-Hard comes as a parquet file;
   convert_bcb.py turns it into the JSONL build.py reads.
2. Google's IFEval checker at the pinned google-research commit, into
   ifeval_checker/instruction_following_eval/ (plus an empty __init__.py),
   with the repository's LICENSE as ifeval_checker/LICENSE and LICENSE beside
   this file. ifeval_checker/local-change.patch (the one local change,
   SOURCE.md) is applied with the stdlib applier below and the result checked
   against its own pin.
3. The fetched checker files are checked against data.lock.

A file that is already present and matches its pin is not downloaded again;
one that is present and does not match is an error (move it aside). The
downloads are never executed, only hashed and patched.

data.lock lists, as `sha256  path` lines relative to this directory (the
`sha256sum` format), every fetched or generated file of the slice.
`build.py --check` verifies the whole tree against it.
"""

